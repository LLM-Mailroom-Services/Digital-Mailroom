def test_cli_list_versions_table_role_and_json(capsys):
    assert main(["prompts", "list-versions", "--role", "sorter"]) == 0
    out = capsys.readouterr().out
    assert [ln.split()[0] for ln in out.splitlines()[2:6]] == ["sorter_v1", "sorter_v2", "sorter_v3", "sorter_v4"]
    assert "eval-env-default" in out and "latest" in out and out.strip().endswith("4 version(s)")
    assert main(["prompts", "list-versions", "--json", "--lineage", "archived"]) == 0
    rows = json.loads(capsys.readouterr().out)
    assert {r["key"] for r in rows} == {v.key for v in ALL if v.lineage == "archived"}
    assert main(["prompts", "list-versions"]) == 0
    assert capsys.readouterr().out.strip().endswith("40 version(s)")


