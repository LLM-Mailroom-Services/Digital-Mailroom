"""Render the eval-environment prompt catalog (``docs/prompts/``) from the dojo lineage.

Every archived, frozen and mutated prompt version with its memo, provenance, what
changed against its predecessor, a unified diff and the full text. The pages are
GENERATED from the vendored dojo lineage (``llm_dojo_scoring.prompts``) by
``scripts/render_prompt_catalog.py`` and are deterministic (no timestamps), so
``--check`` (and ``tests/test_prompt_catalog.py``) fail when they drift from the
vendored dojo. Also backs ``sandbox prompts list-versions`` / ``show``.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Iterable, Mapping

from mailroom_sandbox.paths import repo_root
from mailroom_sandbox.prompt_versions import lineage_api

HEADER = (
    "<!-- GENERATED by scripts/render_prompt_catalog.py from the vendored dojo lineage "
    "(llm_dojo_scoring.prompts, eval-environment {commit}). Do not edit; run "
    "`python scripts/render_prompt_catalog.py` to refresh. -->"
)
README_NAME = "README.md"


def docs_dir() -> Path:
    return repo_root() / "docs" / "prompts"


# ── small helpers ────────────────────────────────────────────────────────────
def _fence(text: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def fenced(text: str, info: str = "text") -> str:
    fence = _fence(text)
    body = text if text.endswith("\n") else text + "\n"
    return f"{fence}{info}\n{body}{fence}"


def first_sentence(memo: str, limit: int = 150) -> str:
    flat = " ".join(memo.split())
    m = re.search(r"(?<=[.!?])\s", flat)
    sentence = flat[: m.start()] if m else flat
    if len(sentence) > limit:
        sentence = sentence[: limit - 1].rstrip() + "…"
    return sentence.replace("|", "\\|")


def _order(versions: Iterable[Any]) -> list[Any]:
    """Oldest -> newest within a role: archived first, then frozen / mutations by version."""
    return sorted(versions, key=lambda v: (v.lineage != "archived", v.version))


def _sandbox_defaults() -> dict[str, dict[str, Any]]:
    """``{role: {key, stem, sha256_ok}}`` for the catalog stems a run gets with no flag."""
    import hashlib

    from mailroom_sandbox import eval_environment_lineage as lin
    from mailroom_sandbox.prompts import load_variant

    out: dict[str, dict[str, Any]] = {}
    for role, row in lin.specialist_rows().items():
        stem = str(row["sandbox_stem"])
        sha = hashlib.sha256(load_variant(stem).encode("utf-8")).hexdigest()
        out[role] = {
            "key": str(row["eval_environment_key"]),
            "stem": stem,
            "sha256_matches_lock": sha == str(row["sha256"]),
        }
    return out


def _eval_tasks() -> set[str]:
    from mailroom_sandbox.eval.agents import SPECS

    return set(SPECS)


def run_commands(role: str, key: str, *, pipeline_roles: set[str], eval_tasks: set[str]) -> list[str]:
    """The exact commands that run ``key`` (empty when the role has no pipeline agent)."""
    if role not in pipeline_roles:
        return []
    cmds = []
    if role in eval_tasks:
        cmds.append(f"sandbox eval {role} --prompt-version {key}")
    else:
        cmds.append(f"sandbox eval pipeline --prompt-version {role}={key}")
    cmds.append(f"sandbox run start --config <run.yaml> --prompt-version {role}={key}")
    return cmds


def _date_notes(chain_by_key: Mapping[str, Any], v: Any) -> list[str]:
    pred = chain_by_key.get(v.predecessor) if v.predecessor else None
    if pred is not None and v.created_at < pred.created_at:
        return [
            f"catalog: created_at {v.created_at} precedes its predecessor {pred.key} ({pred.created_at}); "
            "eval-environment dates are not monotonic with version order"
        ]
    return []


# ── role page ────────────────────────────────────────────────────────────────
def _version_section(
    v: Any,
    *,
    by_key: Mapping[str, Any],
    api: Any,
    defaults: Mapping[str, Any],
    eval_default_key: str | None,
    latest_key: str,
    pipeline_roles: set[str],
    eval_tasks: set[str],
) -> list[str]:
    out = [f"### {v.key}", ""]
    badges = [f"**{v.lineage}**"]
    if defaults.get("key") == v.key:
        badges.append("**sandbox default** (a run with no flag)")
    if eval_default_key == v.key:
        badges.append("**eval-environment default** (`_v1`)")
    if latest_key == v.key:
        badges.append("**latest**")
    out += [" · ".join(badges), ""]
    out += [
        "| field | value |",
        "| --- | --- |",
        f"| key | `{v.key}` |",
        f"| role / version | `{v.role}` / {v.version} |",
        f"| lineage | {v.lineage} |",
        f"| parent | {('`' + v.parent + '`') if v.parent else '—'} |",
        f"| supersedes | {('`' + v.supersedes + '`') if v.supersedes else '—'} |",
        f"| created_at | {v.created_at} |",
        f"| anchor_head | {('`' + json.dumps(v.anchor_head, ensure_ascii=False).replace('|', '\\|') + '`') if v.anchor_head else '—'} |",
        f"| source | `{v.source}` |",
        f"| chars | {v.chars} |",
        f"| sha256 | `{v.sha256}` |",
        "",
        "**Memo**",
        "",
        fenced(v.memo, "text"),
        "",
    ]
    pred = by_key.get(v.predecessor) if v.predecessor else None
    ch = v.changes
    if pred is None or ch is None:
        out += ["**Changes**: none recorded — this version has no predecessor in the lineage.", ""]
        if v.lineage == "archived":
            others = [o for o in by_key.values() if o.role == v.role and o.lineage == "archived" and o.key != v.key]
            for other in sorted(others, key=lambda o: o.version):
                diff = api.diff_prompt_versions(other.key, v.key)
                added = sum(1 for ln in diff.splitlines() if ln.startswith("+") and not ln.startswith("+++"))
                removed = sum(1 for ln in diff.splitlines() if ln.startswith("-") and not ln.startswith("---"))
                out += [
                    f"Also archived for this role: `{other.key}` ({other.chars} chars). "
                    f"Against it this text is +{added}/-{removed} lines, {v.chars - other.chars:+d} chars.",
                    "",
                ]
    else:
        out += [f"**Changes vs `{pred.key}`**", ""]
        sections = list(ch.get("sections_changed") or [])
        out += [
            f"- lines: +{ch.get('lines_added', 0)} / -{ch.get('lines_removed', 0)}",
            f"- chars: {ch.get('chars_delta', 0):+d} ({pred.chars} -> {v.chars})",
        ]
        out.append("- sections changed: " + ("; ".join(f"`{s}`" for s in sections) if sections else "—"))
        notes = list(ch.get("notes") or [])
        if not any("monotonic" in n for n in notes):  # the dojo flags most; never state it twice
            notes += _date_notes(by_key, v)
        if notes:
            out.append("- notes:")
            out += [f"  - {n}" for n in notes]
        out.append("")
        for label, field in (("Added (excerpt)", "added_excerpt"), ("Removed (excerpt)", "removed_excerpt")):
            lines = list(ch.get(field) or [])
            if lines:
                out += [f"**{label}**", "", fenced("\n".join(lines), "text"), ""]
        diff = api.diff_prompt_versions(pred.key, v.key)
        out += [
            f"<details><summary>Unified diff {pred.key} -> {v.key}</summary>",
            "",
            fenced(diff, "diff") if diff else "(identical text)",
            "",
            "</details>",
            "",
        ]
    out += [
        f"<details><summary>Full prompt text ({v.chars} chars)</summary>",
        "",
        fenced(v.text, "text"),
        "",
        "</details>",
        "",
    ]
    cmds = run_commands(v.role, v.key, pipeline_roles=pipeline_roles, eval_tasks=eval_tasks)
    if cmds:
        out += ["**Run it**", "", fenced("\n".join(cmds), "bash"), ""]
    else:
        out += [
            f"**Run it**: not selectable — `{v.role}` is not a sandbox pipeline agent "
            "(`sandbox --prompt-version` refuses it).",
            "",
        ]
    return out


def render_role(role: str, *, commit: str, sandbox_defaults: Mapping[str, Any] | None = None) -> str:
    from mailroom_sandbox.prompt_versions import pipeline_roles

    api = lineage_api()
    versions = _order(api.list_prompt_versions(role=role))
    if not versions:
        raise KeyError(role)
    by_key = {v.key: v for v in api.list_prompt_versions()}
    defaults = (sandbox_defaults or _sandbox_defaults()).get(role, {})
    try:
        eval_default = api.default_prompt_version(role).key
    except KeyError:
        eval_default = None
    latest = api.latest_prompt_version(role).key
    roles = pipeline_roles()
    tasks = _eval_tasks()

    out = [HEADER.format(commit=commit[:7]), "", f"# {role} — prompt versions", ""]
    out += [f"[← all roles]({README_NAME})", ""]
    if defaults:
        mark = "" if defaults.get("sha256_matches_lock") else " (**stem bytes drifted from its lineage lock**)"
        out.append(
            f"- **Sandbox default** (no flag): `{defaults['key']}` via stem "
            f"`config/prompts/{defaults['stem']}.txt`{mark}"
        )
    else:
        out.append("- **Sandbox default** (no flag): none — the vendored mailroom pipeline's own prompt")
    out.append(f"- **eval-environment default**: `{eval_default}`" if eval_default else "- **eval-environment default**: —")
    out.append(f"- **Latest** (highest frozen/mutation): `{latest}`")
    if role not in roles:
        out.append(f"- **Selectable in the sandbox**: no — `{role}` is not a pipeline agent")
    out += ["", "| key | lineage | parent / supersedes | created_at | chars | sha256 |", "| --- | --- | --- | --- | --- | --- |"]
    for v in versions:
        pred = v.predecessor or "—"
        out.append(f"| [{v.key}](#{v.key.lower()}) | {v.lineage} | {pred} | {v.created_at[:10]} | {v.chars} | `{v.sha256[:12]}` |")
    out.append("")
    for v in versions:
        out += _version_section(
            v,
            by_key=by_key,
            api=api,
            defaults=defaults,
            eval_default_key=eval_default,
            latest_key=latest,
            pipeline_roles=roles,
            eval_tasks=tasks,
        )
    return "\n".join(out).rstrip("\n") + "\n"


# ── index ────────────────────────────────────────────────────────────────────
_COLLISIONS = """\
## Names that collide (read this before comparing runs)

eval-environment keys share names with two other sandbox namespaces. They are **different texts**:

- `config/prompts/sorter_v1.txt` (the `--prompt sorter_v1` stem) is the **mailroom** `sorter_v1`
  (entity-extraction lineage), **not** eval-environment `sorter_v1`.
- The vendored mailroom registry `langchain_agents.prompts.PROMPT_VERSIONS` carries
  `sorter_v0 … sorter_v14` and `contracts_specialist_v1 … v33`. That is the entity-extraction lineage,
  unrelated to the eval-environment keys of the same name (the sorter's production lookup key is
  `sorter_v14`; `contracts_specialist_v33` here is an archived re-key of eval-environment `_v0`).

`--prompt-version` therefore resolves eval-environment keys **only from the dojo lineage**
(`llm_dojo_scoring.prompts`, via `mailroom_sandbox.prompt_versions`) — never from the mailroom registry or a
`config/prompts` stem. Records carry the key **and** its sha256 (`prompt_sha256`) and runs are grouped on both,
so one name with different bytes never pools.
"""


def _stems_not_in_lineage(keys: set[str]) -> list[dict[str, Any]]:
    from mailroom_sandbox import eval_environment_lineage as lin

    rows = [dict(r) for r in lin.successor_rows()]
    for role, row in lin.specialist_rows().items():
        rows.append(dict(row, agent=role))
    return [r for r in rows if str(r["eval_environment_key"]) not in keys]


def render_index(*, sandbox_defaults: Mapping[str, Any] | None = None) -> str:
    from mailroom_sandbox.prompt_versions import pipeline_roles

    api = lineage_api()
    source = dict(api.LINEAGE_SOURCE)
    commit = str(source["source_commit"])
    all_versions = api.list_prompt_versions()
    keys = {v.key for v in all_versions}
    defaults = sandbox_defaults or _sandbox_defaults()
    roles = pipeline_roles()
    tasks = _eval_tasks()
    counts = {k: sum(1 for v in all_versions if v.lineage == k) for k in ("archived", "frozen", "mutation")}

    out = [
        HEADER.format(commit=commit[:7]),
        "",
        "# Prompt catalog — every eval-environment prompt version",
        "",
        f"Source: `{source['source_repo']}` @ `{commit[:7]}` (lineage `{source['lineage_id']}`), read through the "
        f"vendored dojo (`llm_dojo_scoring.prompts`). **{len(all_versions)} versions** across "
        f"**{len(api.prompt_roles())} roles**: {counts['archived']} archived, {counts['frozen']} frozen, "
        f"{counts['mutation']} mutations. Each role page has, per version (oldest → newest): metadata, the full memo, "
        "what changed against its predecessor, a unified diff and the full prompt text.",
        "",
        "## Run any version",
        "",
        fenced(
            "sandbox eval correspondence_specialist --prompt-version correspondence_specialist_v3\n"
            "sandbox eval sorter --prompt-version sorter_v4          # bare key: role inferred\n"
            "sandbox eval pipeline --prompt-version sorter_v4 --prompt-version contracts_specialist=contracts_specialist_v2\n"
            "sandbox run start --config <run.yaml> --prompt-version correspondence_specialist_v7\n"
            "# or in the run spec:  prompt: {versions: {sorter: sorter_v4}}\n"
            "\n"
            "sandbox prompts list-versions [--role R]\n"
            "sandbox prompts show <key> [--diff <other-key> | --memo]",
            "bash",
        ),
        "",
        "Unknown keys, a key under the wrong role, and roles that are not pipeline agents "
        "(`pipeline_quality`, `pipeline_verdict`) are refused with an error. With no flag a run is unchanged: "
        "the sandbox default per role is the `*_simplified` stem (marked below).",
        "",
        _COLLISIONS,
        "## Roles",
        "",
    ]
    for role in api.prompt_roles():
        versions = _order(api.list_prompt_versions(role=role))
        d = defaults.get(role, {})
        try:
            eval_default = api.default_prompt_version(role).key
        except KeyError:
            eval_default = None
        latest = api.latest_prompt_version(role).key
        out += [f"### [{role}]({role}.md)", ""]
        flags = []
        flags.append(f"sandbox default: `{d['key']}`" if d else "sandbox default: none (mailroom's own)")
        flags.append(f"eval-environment default: `{eval_default}`" if eval_default else "eval-environment default: —")
        flags.append(f"latest: `{latest}`")
        flags.append("selectable" if role in roles else "**not selectable** (not a pipeline agent)")
        out += ["; ".join(flags), ""]
        out += [
            "| key | lineage | parent / supersedes | created_at | chars | sha256 | memo |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for v in versions:
            tags = []
            if d.get("key") == v.key:
                tags.append("sandbox default")
            if eval_default == v.key:
                tags.append("eval-env default")
            if latest == v.key:
                tags.append("latest")
            label = f"[{v.key}]({role}.md#{v.key.lower()})" + (f" ({', '.join(tags)})" if tags else "")
            out.append(
                f"| {label} | {v.lineage} | {v.predecessor or '—'} | {v.created_at[:10]} | {v.chars} | "
                f"`{v.sha256[:12]}` | {first_sentence(v.memo)} |"
            )
        out.append("")
    extra = _stems_not_in_lineage(keys)
    if extra:
        out += [
            "## Sandbox stems whose eval-environment key is not in the lineage",
            "",
            f"The sandbox lineage lock (`config/prompts/eval_environment_lineage.json`) names these keys, but "
            f"eval-environment `{commit[:7]}` does not catalog them, so `--prompt-version` cannot select them. "
            "Run them by stem with `--prompt <stem>` (or `prompt.agents` in a run spec).",
            "",
            "| key | role | stem | sha256 |",
            "| --- | --- | --- | --- |",
        ]
        for r in extra:
            out.append(
                f"| `{r['eval_environment_key']}` | {r['agent']} | `config/prompts/{r['sandbox_stem']}.txt` | `{str(r['sha256'])[:12]}` |"
            )
        out.append("")
    del tasks
    return "\n".join(out).rstrip("\n") + "\n"


# ── all pages ────────────────────────────────────────────────────────────────
def render_all() -> dict[str, str]:
    """``{relative filename: content}`` for every generated page (deterministic)."""
    api = lineage_api()
    commit = str(api.LINEAGE_SOURCE["source_commit"])
    defaults = _sandbox_defaults()
    pages = {README_NAME: render_index(sandbox_defaults=defaults)}
    for role in api.prompt_roles():
        pages[f"{role}.md"] = render_role(role, commit=commit, sandbox_defaults=defaults)
    return pages


def write(directory: Path | None = None) -> list[Path]:
    target = directory or docs_dir()
    target.mkdir(parents=True, exist_ok=True)
    pages = render_all()
    written = []
    for name, content in pages.items():
        path = target / name
        path.write_text(content, encoding="utf-8")
        written.append(path)
    for stale in sorted(target.glob("*.md")):
        if stale.name not in pages:
            stale.unlink()  # a role the lineage no longer has
    return written


def check(directory: Path | None = None) -> list[str]:
    """Problems between the committed pages and what the vendored dojo renders (empty = in sync)."""
    target = directory or docs_dir()
    pages = render_all()
    problems = []
    for name, content in pages.items():
        path = target / name
        if not path.is_file():
            problems.append(f"missing {path}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"out of date: {path}")
    if target.is_dir():
        for path in sorted(target.glob("*.md")):
            if path.name not in pages:
                problems.append(f"stale (no such role): {path}")
    return problems


# ── CLI backing: `sandbox prompts list-versions` / `show <key>` ──────────────
def is_version_key(name: str) -> bool:
    """True when ``name`` is shaped like a lineage key (``<role>_v<N>``) rather than an agent name."""
    return bool(re.search(r"_v\d+$", str(name)))


def version_row(v: Any, *, defaults: Mapping[str, Any], eval_default: str | None, latest: str) -> dict[str, Any]:
    tags = []
    if defaults.get("key") == v.key:
        tags.append("sandbox-default")
    if eval_default == v.key:
        tags.append("eval-env-default")
    if latest == v.key:
        tags.append("latest")
    return {
        "key": v.key,
        "role": v.role,
        "version": v.version,
        "lineage": v.lineage,
        "predecessor": v.predecessor,
        "created_at": v.created_at,
        "chars": v.chars,
        "sha256": v.sha256,
        "tags": tags,
    }


def list_versions(role: str | None = None, lineage: str | None = None) -> list[dict[str, Any]]:
    """Catalog rows (role, then oldest -> newest). An unknown role raises ``KeyError`` with the roles."""
    api = lineage_api()
    if role is not None and role not in api.prompt_roles():
        raise KeyError(f"unknown role {role!r}; roles: {', '.join(api.prompt_roles())}")
    defaults = _sandbox_defaults()
    rows = []
    for r in ([role] if role else api.prompt_roles()):
        try:
            eval_default = api.default_prompt_version(r).key
        except KeyError:
            eval_default = None
        latest = api.latest_prompt_version(r).key
        for v in _order(api.list_prompt_versions(role=r, lineage=lineage)):
            rows.append(version_row(v, defaults=defaults.get(r, {}), eval_default=eval_default, latest=latest))
    return rows


def format_version_table(rows: list[Mapping[str, Any]]) -> str:
    header = f"{'key':<38} {'lineage':<9} {'predecessor':<38} {'created':<10} {'chars':>6}  {'sha256':<12}  tags"
    lines = [header, "-" * len(header)]
    for r in rows:
        lines.append(
            f"{r['key']:<38} {r['lineage']:<9} {(r['predecessor'] or '-'):<38} {r['created_at'][:10]:<10} "
            f"{r['chars']:>6}  {r['sha256'][:12]:<12}  {', '.join(r['tags'])}"
        )
    lines.append(f"{len(rows)} version(s)")
    return "\n".join(lines)


def show_version(key: str, *, memo_only: bool = False, diff_against: str | None = None) -> str:
    """Text for ``sandbox prompts show <key>``: metadata + text, or memo + changes, or a diff to another key."""
    api = lineage_api()
    v = api.get_prompt_version(key)  # KeyError with close matches
    if diff_against is not None:
        return api.diff_prompt_versions(key, diff_against) or f"(texts of {key} and {diff_against} are identical)\n"
    meta = [
        f"key:        {v.key}",
        f"role:       {v.role} (v{v.version}, {v.lineage})",
        f"parent:     {v.parent or '-'}    supersedes: {v.supersedes or '-'}",
        f"created_at: {v.created_at}    chars: {v.chars}",
        f"sha256:     {v.sha256}",
        f"source:     {v.source}",
    ]
    ch = v.changes
    changes = []
    if ch is not None:
        changes = [
            f"changes vs {ch.get('against')}: +{ch.get('lines_added', 0)}/-{ch.get('lines_removed', 0)} lines, "
            f"{ch.get('chars_delta', 0):+d} chars",
            "sections:   " + ("; ".join(ch.get("sections_changed") or []) or "-"),
        ] + [f"note:       {n}" for n in ch.get("notes") or []]
    if memo_only:
        return "\n".join(meta + changes + ["", "memo:", v.memo]) + "\n"
    return "\n".join(meta + changes + ["", "-" * 72, v.text]) + ("" if v.text.endswith("\n") else "\n")


def version_json(key: str) -> dict[str, Any]:
    v = lineage_api().get_prompt_version(key)
    return {
        "key": v.key,
        "role": v.role,
        "version": v.version,
        "lineage": v.lineage,
        "parent": v.parent,
        "supersedes": v.supersedes,
        "memo": v.memo,
        "anchor_head": v.anchor_head,
        "created_at": v.created_at,
        "source": v.source,
        "sha256": v.sha256,
        "chars": v.chars,
        "changes": dict(v.changes) if v.changes is not None else None,
        "text": v.text,
    }
