def test_index_lists_every_version_with_defaults_and_collisions():
    index = (repo_root() / "docs" / "prompts" / "README.md").read_text(encoding="utf-8")
    for v in ALL:
        assert f"[{v.key}]({v.role}.md#{v.key.lower()})" in index
        assert v.sha256[:12] in index
    assert "40 versions" in index and "15 roles" in index
    # the sandbox / eval-env defaults and "latest" are marked
    assert "[correspondence_specialist_v7](correspondence_specialist.md#correspondence_specialist_v7) (sandbox default, latest)" in index
    assert "[sorter_v1](sorter.md#sorter_v1) (eval-env default)" in index
    assert "[sorter_v4](sorter.md#sorter_v4) (latest)" in index
    # name collisions are explained
    assert "config/prompts/sorter_v1.txt" in index and "not** eval-environment `sorter_v1`" in index
    assert "PROMPT_VERSIONS" in index and "sorter_v14" in index and "contracts_specialist_v33" in index
    assert "only from the dojo lineage" in index
    # sandbox stems whose key the lineage lacks are listed, not hidden
    assert "insurance_claims_specialist_v4" in index and "merger_agreement_specialist_v4" in index


def test_role_page_has_everything_per_version():
    page = (repo_root() / "docs" / "prompts" / "sorter.md").read_text(encoding="utf-8")
    keys = [m.group(1) for m in re.finditer(r"^### (\S+)$", page, re.M)]
    assert keys == ["sorter_v1", "sorter_v2", "sorter_v3", "sorter_v4"]  # oldest -> newest
    for v in [v for v in ALL if v.role == "sorter"]:
        assert v.memo in page  # the FULL memo
        assert f"`{v.sha256}`" in page
        assert f"sandbox eval sorter --prompt-version {v.key}" in page
        assert f"sandbox run start --config <run.yaml> --prompt-version sorter={v.key}" in page
    assert page.count("<details><summary>Unified diff") == 3  # v2, v3, v4 vs their predecessors
    assert page.count("<details><summary>Full prompt text") == 4
    assert "Changes vs `sorter_v2`" in page and "chars: +667 (18854 -> 19521)" in page
    # the dojo-flagged duplicate block and the non-monotonic dates are called out
    assert "duplicated block" in page and "not monotonic" in page
    assert "**eval-environment default** (`_v1`)" in page and "**latest**" in page


