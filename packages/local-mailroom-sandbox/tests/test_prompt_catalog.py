def test_check_script_passes_and_flags_drift(tmp_path):
    script = repo_root() / "scripts" / "render_prompt_catalog.py"
    ok = subprocess.run([sys.executable, str(script), "--check"], capture_output=True, text=True)
    assert ok.returncode == 0, ok.stderr
    assert "in sync" in ok.stdout
    # a stale / edited copy is reported (library level, so no file is rewritten in the repo)
    copy = tmp_path / "prompts"
    copy.mkdir()
    for name, content in catalog.render_all().items():
        (copy / name).write_text(content, encoding="utf-8")
    (copy / "sorter.md").write_text("edited by hand\n", encoding="utf-8")
    (copy / "retired_role.md").write_text("x\n", encoding="utf-8")
    (copy / "boss.md").unlink()
    problems = catalog.check(copy)
    assert any("out of date" in p and "sorter.md" in p for p in problems)
    assert any("missing" in p and "boss.md" in p for p in problems)
    assert any("stale" in p and "retired_role.md" in p for p in problems)


def test_rendering_is_deterministic_and_marked_generated():
    first, second = catalog.render_all(), catalog.render_all()
    assert first == second
    assert set(first) == {"README.md", *(f"{r}.md" for r in prompt_roles())}
    for name, content in first.items():
        assert content.startswith("<!-- GENERATED by scripts/render_prompt_catalog.py"), name
        assert content.endswith("\n") and not content.endswith("\n\n"), name
        assert not re.search(r"20\d\d-\d\d-\d\dT.*render", content), "no render-time timestamps"


