#!/usr/bin/env python3
"""Generate/check the argparse-derived CLI reference without running commands."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

from mailroom_sandbox.cli import build_parser  # noqa: E402

REFERENCE = ROOT / 'docs' / 'cli-reference.md'


def children(parser, *, hidden=True):
    """Subcommands; ``hidden=False`` drops ones marked ``_sandbox_hidden`` (still parsed and tested)."""
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, child in action.choices.items():
                if hidden or not getattr(child, '_sandbox_hidden', False):
                    yield name, child


def nodes(parser, path=(), *, hidden=True):
    yield path, parser
    for name, child in children(parser, hidden=hidden):
        yield from nodes(child, (*path, name), hidden=hidden)


def required(action):
    if isinstance(action, argparse._SubParsersAction):
        return False
    if action.option_strings:
        return bool(action.required)
    # Positionals: derive from nargs, not ``action.required`` -- Python < 3.12 marks
    # ``nargs='*'`` positionals required even though parsing accepts zero values.
    return action.nargs not in ('?', '*', argparse.REMAINDER)


def risk(path):
    """Conservative orientation only; options and configuration can change effects."""
    command = ' '.join(path)
    if not path:
        return 'Varies by subcommand'
    if path[0] in {'modal', 'vllm', 'hf', 'up', 'down', 'health', 'pull-models', 'fetch-deps', 'tunnel', 'pipeline', 'review', 'tui'}:
        return 'May invoke services, network, deployment, or local processes'
    if path[0] in {'experiment', 'run', 'watch', 'dev', 'board'}:
        return 'May write files, run jobs, serve a UI, or contact services'
    if path[0] in {'datasets', 'traces', 'beacon', 'subagents'}:
        return 'May write files or contact services'
    if path[0] in {'eval', 'pilot', 'hf-pilot', 'matrix'}:
        return 'May run inference or write results; mock/dry-run options vary'
    if command.startswith('metrics serving-record') or command.startswith('runbook write'):
        return 'May write files'
    return 'Inspect help and implementation for side effects'


def escape(value):
    return str(value).replace('|', r'\|').replace('\n', ' ')


def render(parser):
    all_nodes = list(nodes(parser, hidden=False))
    leaves = [(path, p) for path, p in all_nodes if not list(children(p, hidden=False))]
    lines = [
        '# CLI reference', '',
        '<!-- Generated by scripts/check_cli_surface.py; do not edit by hand. -->', '',
        f'This reference lists {len(all_nodes)} parser nodes including the root and {len(leaves)} leaves. '
        'It is generated from argparse help and describes the parser surface, not a certification of handler behavior.', '',
        'Tests exercise help, parser-required arguments, and dispatch with handlers replaced by stubs. '
        'They do not execute live inference, deployments, endpoint calls, destructive operations, or verify external dependencies. '
        'Required markers cover argparse requirements only; handlers may impose additional prerequisites. '
        'Consult command help and the relevant runbook before execution; defaults and configuration can affect side effects.', '',
        'Behavioral checks are maintained separately, including `tests/test_cli_audit_regressions.py`, '
        '`tests/test_eval.py`, `tests/test_job_cli.py`, `tests/test_experiments.py`, and the service CLI tests. '
        'These offline tests do not establish that live services or credentials are available.', '',
        'Regenerate with `python scripts/check_cli_surface.py`; verify with `python scripts/check_cli_surface.py --check`.', '',
        '## Commands', '',
    ]
    for path, p in all_nodes:
        title = 'sandbox' + ((' ' + ' '.join(path)) if path else '')
        subs = list(children(p, hidden=False))
        hidden = [name for name, _ in children(p) if name not in dict(subs)]
        lines.extend([f'### `{title}`', '', f'**Scope:** {risk(path)}.', ''])
        if p.description:
            lines.extend([escape(p.description), ''])
        if subs:
            lines.extend(['**Subcommands:** ' + ', '.join(f'`{escape(name)}`' for name, _ in subs) + '.', ''])
        if hidden:
            lines.extend([f'**Also accepted (not primary; hidden from help and menus):** {len(hidden)} legacy subcommands, '
                          f'listed by `{title} --all-tasks`.', ''])
        actions = [a for a in p._actions if not isinstance(a, argparse._SubParsersAction) and a.help is not argparse.SUPPRESS]
        if actions:
            lines.extend(['| Argument | Required by parser | Description |', '| --- | --- | --- |'])
            for action in actions:
                name = ', '.join(action.option_strings) if action.option_strings else action.dest
                help_text = (action.help or '').replace('%(default)s', str(action.default)).replace('%(prog)s', p.prog)
                if action.choices is not None:
                    help_text += (' ' if help_text else '') + 'Choices: ' + ', '.join(map(str, action.choices)) + '.'
                lines.append(f'| `{escape(name)}` | {"Yes" if required(action) else "No"} | {escape(help_text)} |')
            lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if reference is stale')
    args = parser.parse_args()
    generated = render(build_parser())
    if args.check:
        if not REFERENCE.is_file() or REFERENCE.read_text(encoding='utf-8') != generated:
            print('CLI reference is stale; run python scripts/check_cli_surface.py', file=sys.stderr)
            return 1
        print('CLI reference is current')
        return 0
    REFERENCE.write_text(generated, encoding='utf-8')
    print(f'Wrote {REFERENCE.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
