def test_cli_show_key_memo_diff_json(capsys):
    assert main(["prompts", "show", "sorter_v4"]) == 0
    out = capsys.readouterr().out
    assert "key:        sorter_v4" in out and "CORPORATE RECORD SUBCLASS" in out
    sorter_v4 = [v for v in ALL if v.key == "sorter_v4"][0]
    assert sorter_v4.text in out

    assert main(["prompts", "show", "sorter_v4", "--memo"]) == 0
    memo = capsys.readouterr().out
    assert sorter_v4.memo in memo and "duplicate removed" in memo and sorter_v4.text not in memo

    assert main(["prompts", "show", "sorter_v3", "--diff", "sorter_v4"]) == 0
    diff = capsys.readouterr().out
    assert diff.startswith("--- sorter_v3\n+++ sorter_v4\n") and "-Assign the correct subclass key." in diff

    assert main(["prompts", "show", "sorter_v4", "--json"]) == 0
    data = json.loads(capsys.readouterr().out)
    assert data["sha256"] == sorter_v4.sha256 and data["text"] == sorter_v4.text and data["parent"] == "sorter_v3"


